/**
 * Inlines the generated Drizzle migrations into a plain TypeScript module.
 *
 * drizzle-kit emits `drizzle/migrations.js`, which imports each `.sql` file as
 * a module. That only works because Wrangler is configured to bundle `.sql` as
 * a Text module — a `rules` entry that every consumer of this agent would have
 * to replicate in their own wrangler config for the package to build at all.
 *
 * Emitting the SQL as ordinary string literals removes that requirement: the
 * agent becomes an npm dependency you can import with no bundler
 * configuration, and this repository loses a gotcha it had to document.
 *
 * Run after `drizzle-kit generate`; `npm run migrations` does both.
 */
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const drizzleDir = path.join(here, '..', 'drizzle');
const outFile = path.join(here, '..', 'src', 'migrations.ts');

const journalPath = path.join(drizzleDir, 'meta', '_journal.json');
if (!fs.existsSync(journalPath)) {
	console.error(`No journal at ${journalPath} — run \`npx drizzle-kit generate\` first.`);
	process.exit(1);
}

const journal = JSON.parse(fs.readFileSync(journalPath, 'utf8'));
const entries = journal.entries ?? [];

/** Backtick-safe: migrations are SQL, but never assume about generated text. */
function toTemplateLiteral(sql) {
	return '`' + sql.replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$\{/g, '\\${') + '`';
}

const parts = [];
for (const entry of entries) {
	const file = path.join(drizzleDir, `${entry.tag}.sql`);
	if (!fs.existsSync(file)) {
		console.error(`Journal lists ${entry.tag} but ${file} is missing.`);
		process.exit(1);
	}
	const key = `m${String(entry.idx).padStart(4, '0')}`;
	parts.push({ key, sql: fs.readFileSync(file, 'utf8') });
}

const banner = `// Generated by scripts/generate-migrations.mjs — do not edit.
//
// The SQL is inlined rather than imported from .sql files so this agent can be
// consumed as a plain npm dependency, with no Wrangler Text-module rule needed
// in the consumer's config. Regenerate with \`npm run migrations\`.
`;

// No `as const`: drizzle's MigrationConfig takes a mutable entries array, and a
// readonly tuple is not assignable to it.
const body = `
const journal = ${JSON.stringify(journal, null, '\t')};

${parts.map((p) => `const ${p.key} = ${toTemplateLiteral(p.sql)};`).join('\n\n')}

export default {
	journal,
	migrations: {
${parts.map((p) => `\t\t${p.key}`).join(',\n')}
	}
};
`;

fs.writeFileSync(outFile, `${banner}${body}`, 'utf8');
console.log(
	`Inlined ${parts.length} migration${parts.length === 1 ? '' : 's'} into src/migrations.ts`,
);
